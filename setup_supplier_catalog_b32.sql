create table if not exists supplier_items(
  id        bigint generated by default as identity primary key,
  sup_sheet text not null,
  sup_full  text,
  name      text not null,
  unit      text,
  has_vat   boolean default false,
  has_disc  boolean default false,
  sort      int default 0,
  active    boolean default true
);
create unique index if not exists supplier_items_uk on supplier_items(sup_sheet, name);

create table if not exists supplier_map(
  sup_sheet text primary key,
  sup_app   text,
  updated_at timestamptz default now()
);

alter table supplier_items enable row level security;
alter table supplier_map   enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where tablename='supplier_items' and policyname='sit_rw') then
    create policy sit_rw on supplier_items for all to anon, authenticated using (true) with check (true);
  end if;
  if not exists (select 1 from pg_policies where tablename='supplier_map' and policyname='smp_rw') then
    create policy smp_rw on supplier_map for all to anon, authenticated using (true) with check (true);
  end if;
end $$;
grant select, insert, update, delete on public.supplier_items to anon, authenticated;
grant select, insert, update, delete on public.supplier_map   to anon, authenticated;
grant select on public.supplier_items to service_role;
grant select on public.supplier_map   to service_role;
do $$ declare s text; begin
  s := pg_get_serial_sequence('public.supplier_items','id');
  if s is not null then execute 'grant usage, select on '||s||' to anon, authenticated'; end if;
end $$;

